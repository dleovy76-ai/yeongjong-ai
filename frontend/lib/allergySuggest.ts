// 재료/원산지에 사장님이 직접 적어둔(=사실로 취급되는) 텍스트에서, 흔히 알려진
// 알레르기 유발 성분 키워드를 단순 매칭으로 뽑아 "초안"만 만들어준다 - LLM
// 호출이 아니라 결정적(deterministic) 문자열 매칭이라 지어낼 여지가 없다.
// 참고용 매칭일 뿐 식품 표시 규정의 공식 목록을 그대로 옮긴 게 아니므로,
// 사장님이 반드시 확인하고 저장해야 한다(§29와 같은 원칙 - AI/자동 매칭
// 결과를 곧바로 사실로 취급하지 않음).
const _ALLERGEN_KEYWORDS: [string[], string][] = [
  [["새우"], "새우"],
  [["꽃게", "대게", "게살", "게장"], "게"],
  [["조개", "굴", "전복", "홍합"], "조개류"],
  [["오징어"], "오징어"],
  [["고등어"], "고등어"],
  [["우유", "치즈", "버터", "생크림"], "우유"],
  [["계란", "달걀", "난류"], "난류(계란)"],
  [["메밀"], "메밀"],
  [["밀가루", "밀"], "밀"],
  [["대두", "두부", "콩"], "대두"],
  [["땅콩"], "땅콩"],
  [["호두"], "호두"],
  [["잣"], "잣"],
  [["돼지고기", "돼지"], "돼지고기"],
  [["쇠고기", "소고기"], "쇠고기"],
  [["닭고기", "닭"], "닭고기"],
  [["토마토"], "토마토"],
  [["복숭아"], "복숭아"],
  [["아황산"], "아황산류"],
];

export function suggestAllergyInfo(originInfo: string): string {
  const matched: string[] = [];
  for (const [keywords, label] of _ALLERGEN_KEYWORDS) {
    if (keywords.some((k) => originInfo.includes(k)) && !matched.includes(label)) {
      matched.push(label);
    }
  }
  return matched.join(", ");
}
